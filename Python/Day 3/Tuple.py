# Tuples - it is a data type which is immutable and store sequence of values.

tup1 = (87, 64, 33, 95, 76)

# Tuple methods - most are same as list.

tup = (1, 2, 3, 7, 3, 2, 3)

# index - return index of first occurence.
print(tup.index(3))

# count - counts the total number of occurence.
print(tup.count(3))
